export function priorityLabel(p: number, lang: Lang): string {
  if (p >= 5) return translate('high', lang);
  if (p >= 3) return translate('medium', lang);
  if (p >= 1) return translate('low', lang);
  return translate('none', lang);
}

export function statusLabel(s: string, lang: Lang): string {
  if (s === 'completed') return translate('completed', lang);
  if (s === 'abandoned') return translate('abandoned', lang);
  return translate('open', lang);
}
