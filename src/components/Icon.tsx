export function iconName(value: string | null | undefined, fallback = 'folder'): string {
  if (!value) return fallback;
  const trimmed = value.trim();
  if (REGISTRY[trimmed]) return trimmed;
  if (LEGACY[trimmed]) return LEGACY[trimmed];
  // Unknown emoji/character: fall back rather than rendering a broken glyph.
  if (/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}]/u.test(trimmed)) return fallback;
  return fallback;
}

export function Icon({
  name,
  size = 17,
  strokeWidth = 1.9,
  className,
  style,
  color,
}: {
  name: string | null | undefined;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
  color?: string;
}) {
  const Component = REGISTRY[iconName(name)] ?? Folder;
  return <Component size={size} strokeWidth={strokeWidth} className={className} style={style} color={color} aria-hidden="true" />;
}

export function IconPicker({
  value,
  onChange,
  label,
}: {
  value: string;
  onChange: (name: string) => void;
  label?: string;
}) {
  return (
    <div className="icon-picker">
      {label ? <span className="small muted">{label}</span> : null}
      <div className="icon-picker-grid">
        {ICON_CHOICES.map((choice) => (
          <button
            key={choice.name}
            type="button"
            className={`icon-choice ${iconName(value) === choice.name ? 'active' : ''}`}
            title={choice.ar}
            onClick={() => onChange(choice.name)}
          >
            <Icon name={choice.name} size={18} />
          </button>
        ))}
      </div>
    </div>
  );
}
